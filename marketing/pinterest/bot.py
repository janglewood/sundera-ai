async def post_init(app: Application):
    # Populates the client's "/" command menu — separate surface from main_menu_keyboard()'s
    # bottom buttons, doesn't hurt to have both.
    await app.bot.set_my_commands([
        BotCommand("start", "Show the button menu"),
        BotCommand("status", "Batch/refill status"),
        BotCommand("run", "Start a candidate/generation batch now"),
        BotCommand("run_parse", "Scrape + classify + FLUX-clean now (full refill)"),
        BotCommand("run_classify", "Sort/classify unclassified photos now (skip scrape/clean)"),
        BotCommand("run_clean", "FLUX-clean photos/watermark/ now (skip scrape/classify)"),
        BotCommand("run_publish", "Ask to publish the next queued pin now (still needs your Approve)"),
    ])
    st = state.load()
    today = datetime.now(TZ).strftime("%Y-%m-%d")
    if st["stage"] in ("candidates", "generating") and st["current"]:
        current = st["current"]
        photo_path = os.path.join(pipeline.PHOTOS_DIR, current["photo_file"])
        day_rolled_over = st["date"] != today
        photo_missing = not os.path.exists(photo_path)
        if day_rolled_over or photo_missing:
            reason = (
                "the day rolled over mid-batch"
                if day_rolled_over
                else "its before-photo is missing from photos/clean/"
            )
            await app.bot.send_message(
                CHAT_ID,
                f"Restarted and {reason} — dropping the incomplete batch, "
                "starting fresh at the next scheduled time.",
            )
            # Preserve every field independent of the candidate/generation batch being
            # dropped here — refill_stage/last_refill_check_date (own daily schedule) and
            # everything publish-related (own daily schedule + approval gate, see
            # publish_scheduler_loop/pending_publish) would otherwise be silently wiped by
            # dict(state.DEFAULT_STATE).
            preserved = {
                k: st[k] for k in (
                    "refill_stage", "last_refill_check_date",
                    "publish_queue", "publish_date", "publish_times_today",
                    "publish_times_done", "pending_publish",
                )
            }
            st = dict(state.DEFAULT_STATE)
            st.update(preserved)
            st["next_run_at"] = next_run_after(datetime.now(TZ)).isoformat()
            state.save(st)
        else:
            await app.bot.send_message(CHAT_ID, "Resuming after a restart — re-sending the pending item.")
            if st["stage"] == "candidates":
                await send_candidate(app, current)
            elif current.get("pending_generation"):
                # Crashed mid-OpenRouter-call before any result existed — nothing to
                # re-send, just re-run generation for this slot from scratch, with the
                # same style that was already locked in (chosen or rolled) before the crash.
                base_slot = {
                    "photo_id": current["photo_id"],
                    "photo_file": current["photo_file"],
                    "room_type": current["room_type"],
                }
                await generate_and_send(app, base_slot, style=current.get("style"))
            else:
                room_label = pipeline.room_label(current["room_type"])
                collage_bytes = base64.b64decode(current["collage_b64"])
                msg = await app.bot.send_photo(
                    CHAT_ID,
                    io.BytesIO(collage_bytes),
                    caption=(
                        f"Result {st['slot_index'] + 1}/{BATCH_SIZE} — {room_label}, {current['style_label']}\n"
                        "Approve to save to R2, or reject to regenerate with a different style."
                    ),
                    reply_markup=decision_keyboard(),
                )
                st = state.load()
                st["current"]["message_id"] = msg.message_id
                state.save(st)

    # Independent of the candidate/generation stage above — a pending Pinterest publish
    # decision survives a restart in state.py, and the old message's buttons would still
    # technically work (callback_data is self-contained), but resend fresh for visibility
    # rather than relying on Anton noticing an old message.
    st = state.load()
    if st["pending_publish"]:
        pending = st["pending_publish"]
        if os.path.exists(pending["image_path"]):
            await app.bot.send_message(
                CHAT_ID, "Resuming after a restart — re-sending the pending Pinterest publish decision."
            )
            await send_publish_approval(app, {k: v for k, v in pending.items() if k != "message_id"})
        else:
            await app.bot.send_message(
                CHAT_ID,
                f"Restarted — the pending Pinterest publish item \"{pending['title']}\" is missing its "
                "local image file, dropping it.",
            )
            st["pending_publish"] = None
            state.save(st)

    asyncio.create_task(scheduler_loop(app))
    asyncio.create_task(refill_scheduler_loop(app))
    asyncio.create_task(publish_scheduler_loop(app))


def main():
    # Python 3.14 dropped asyncio.get_event_loop()'s implicit loop creation on the
    # main thread, which python-telegram-bot 21.x's run_polling() still relies on.
    try:
        asyncio.get_event_loop()
    except RuntimeError:
        asyncio.set_event_loop(asyncio.new_event_loop())

    app = Application.builder().token(ENV["TELEGRAM_BOT_TOKEN"]).post_init(post_init).build()
    app.add_handler(CommandHandler("start", on_start))
    app.add_handler(CommandHandler("status", on_status))
    app.add_handler(CommandHandler(["run", "run_generation"], on_run))
    app.add_handler(CommandHandler("run_parse", on_run_parse))
    app.add_handler(CommandHandler("run_classify", on_run_classify))
    app.add_handler(CommandHandler("run_clean", on_run_clean))
    app.add_handler(CommandHandler("run_publish", on_run_publish))
    app.add_handler(CallbackQueryHandler(on_callback))
    app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, on_text))
    logger.info(
        "Starting bot: batch_size=%s schedule=%02d:%02d UTC%+g",
        BATCH_SIZE, SCHEDULE_HOUR, SCHEDULE_MINUTE, float(ENV["SCHEDULE_UTC_OFFSET"]),
    )
    app.run_polling(allowed_updates=Update.ALL_TYPES)


if __name__ == "__main__":
    main()
