#!/usr/bin/env python3
"""Daily Telegram-approval daemon for the Sundera Pinterest pipeline.

Runs forever. Once a day (SCHEDULE_TIME, in a fixed UTC+SCHEDULE_UTC_OFFSET
timezone) it starts a batch of BATCH_SIZE (default 3) pins, strictly one
slot at a time:

  Candidate — send an unused "before" photo with a button per DesignStyle,
  plus a "different photo" button. Tapping a style immediately starts
  generation with that style (no more random style assignment); "different
  photo" swaps in a different candidate for the same slot without
  generating anything.

  Generation — call OpenRouter with the chosen style, build the
  before/after collage, send it for Approve/Reject (inline button or typed
  "approve"/"reject"). Approve uploads before/after/collage to R2 (see
  storage_r2.py), replies with a link, and moves on to the next slot's
  candidate. Reject re-generates the same candidate with a different
  (randomly chosen) style and sends again.

After BATCH_SIZE approved collages, sleeps until the next scheduled run.
Send /run or /run_generation to start a batch immediately instead of
waiting for SCHEDULE_TIME (no-op with a warning if one is already in
progress); /run_parse starts a pool refill immediately instead of waiting
for REFILL_CHECK_TIME, skipping the yes/no prompt (independent of the
other schedule — can run alongside an in-progress batch); /status reports
stage/slot/next-run-time plus the clean-pool count and refill_stage.

Candidates are drawn from photos/clean/ on disk (see kufar_collect.py,
classify_photos.py, refill_pool.py — the Kufar-scrape pipeline that
replaced Pexels as the "before" photo source, 2026-09-25). A photo is
deleted the moment it's "used": a rejected candidate is gone for good, and
an approved generated result's source photo is removed once it's archived
to R2 under pinterest/ (see upload_and_reply) — the local copy is then
redundant. Separately, once a day at REFILL_CHECK_TIME (default 21:30),
refill_scheduler_loop checks whether photos/clean/ has fewer than
REFILL_THRESHOLD (default 20) photos left and, if so, asks in Telegram
whether to run a fresh scrape->classify->clean cycle (refill_pool.py) —
only starts on explicit yes, runs in a background thread (it's a multi-hour
job), and the bot stays fully responsive to Telegram throughout.

This process runs locally on this Mac, not deployed to Railway — the
classification (Ollama) and watermark-cleanup (rapid-mlx/FLUX) steps in
refill_pool.py only exist locally, a Railway container can't reach them.
The Dockerfile/Railway deploy docs below are stale as of that same date,
kept only in case of a future revert to a Pexels-only, Railway-deployed setup.

All progress is persisted to SQLite (state.py) after every step, so a
restart resumes mid-batch instead of losing progress or re-spending an
OpenRouter call on an already-generated image.

Pinterest publishing (2026-10-07, see pinterest_publish.py and CLAUDE.md for why this is
browser automation, not the official API): every approved pin is appended to
publish_queue (collage written to output/to_publish/, title/description/link already
generated by upload_and_reply) instead of publishing immediately. publish_scheduler_loop
is a third independent schedule — PUBLISH_TIMES_PER_DAY (default 3) random times/day
within [PUBLISH_WINDOW_START, PUBLISH_WINDOW_END) (default 09:00-21:00) — that pops the
queue and sends it to Anton for Approve/Discard (send_publish_approval,
pending_publish in state.py) rather than publishing it directly. **A real
pinterest_publish.publish_pin() call only ever happens from handle_publish_decision's
approved branch (2026-10-08) — the scheduler, /run_publish, and a restart-resume all route
through this same approval gate, no path calls publish_pin() unattended.** A failed
publish goes back to the front of the queue (gets a fresh approval prompt next slot, not
retried silently) and alerts in Telegram either way. Needs a one-time manual
`./.venv/bin/python pinterest_publish.py login` (or `import-cookies` for a Google-OAuth
account — see CLAUDE.md) before anything in the queue can actually publish — bot.py never
touches Pinterest credentials itself. /run_publish sends the queue head for approval
immediately, ignoring the schedule — it does not publish by itself either.

Config: marketing/pinterest/.env — TELEGRAM_BOT_TOKEN, TELEGRAM_CHAT_ID
required; OPENROUTER_*/R2_* per pipeline.py/storage_r2.py; SCHEDULE_TIME
(default "11:00"), SCHEDULE_UTC_OFFSET (default "3"), BATCH_SIZE
(default "3"), REFILL_THRESHOLD (default "20"), REFILL_CHECK_TIME
(default "21:30"), PINTEREST_BOARD_NAME (optional — empty posts straight
to the profile, this account has no boards), PUBLISH_TIMES_PER_DAY
(default "3"), PUBLISH_WINDOW_START/PUBLISH_WINDOW_END (default
"09:00"/"21:00") optional. See .env.example.

Run: ./.venv/bin/python bot.py
"""
