def load_bot_env():
    env = pipeline.read_env_file(pipeline.LOCAL_ENV_PATH)
    for key in ("TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID"):
        env[key] = os.environ.get(key, env.get(key, ""))
    missing = [k for k in ("TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID") if not env[k]]
    if missing:
        sys.exit(f"Missing {', '.join(missing)} in marketing/pinterest/.env — see .env.example")
    env["SCHEDULE_TIME"] = os.environ.get("SCHEDULE_TIME", env.get("SCHEDULE_TIME") or "11:00")
    env["SCHEDULE_UTC_OFFSET"] = os.environ.get("SCHEDULE_UTC_OFFSET", env.get("SCHEDULE_UTC_OFFSET") or "3")
    env["BATCH_SIZE"] = os.environ.get("BATCH_SIZE", env.get("BATCH_SIZE") or "3")
    env["REFILL_THRESHOLD"] = os.environ.get("REFILL_THRESHOLD", env.get("REFILL_THRESHOLD") or "20")
    env["REFILL_CHECK_TIME"] = os.environ.get("REFILL_CHECK_TIME", env.get("REFILL_CHECK_TIME") or "21:30")
    # Pinterest publishing (pinterest_publish.py, browser automation — see CLAUDE.md).
    # PINTEREST_BOARD_NAME is optional — empty means pins publish straight to the profile
    # (no boards set up on this account, confirmed 2026-10-08); if set, must exactly match
    # an existing board's visible name.
    env["PINTEREST_BOARD_NAME"] = os.environ.get("PINTEREST_BOARD_NAME", env.get("PINTEREST_BOARD_NAME") or "")
    env["PUBLISH_TIMES_PER_DAY"] = os.environ.get("PUBLISH_TIMES_PER_DAY", env.get("PUBLISH_TIMES_PER_DAY") or "3")
    env["PUBLISH_WINDOW_START"] = os.environ.get("PUBLISH_WINDOW_START", env.get("PUBLISH_WINDOW_START") or "09:00")
    env["PUBLISH_WINDOW_END"] = os.environ.get("PUBLISH_WINDOW_END", env.get("PUBLISH_WINDOW_END") or "21:00")
    return env


