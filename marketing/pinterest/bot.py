async def refill_scheduler_loop(app):
    """Independent of scheduler_loop's candidate/generation stage — checks once a day at
    REFILL_CHECK_TIME (default 21:30) whether photos/clean/ is running low, regardless of
    whether today's SCHEDULE_TIME batch is idle, in progress, or done."""
    while True:
        await asyncio.sleep(300)
        st = state.load()
        if st["refill_stage"] != "idle":
            continue
        now = datetime.now(TZ)
        today = now.strftime("%Y-%m-%d")
        if st["last_refill_check_date"] == today:
            continue
        if (now.hour, now.minute) < (REFILL_CHECK_HOUR, REFILL_CHECK_MINUTE):
            continue
        count = len(pipeline.load_manifest(source_dir="clean"))
        st["last_refill_check_date"] = today
        if count < REFILL_THRESHOLD:
            st["refill_stage"] = "awaiting_confirmation"
            state.save(st)
            await app.bot.send_message(
                CHAT_ID,
                f"photos/clean/ has {count} photos left (< {REFILL_THRESHOLD}). Run a fresh "
                "scrape -> classify -> clean cycle? This can take several hours.",
                reply_markup=refill_keyboard(),
            )
        else:
            state.save(st)


def pick_publish_times(now):
    """PUBLISH_TIMES_PER_DAY random datetimes within [PUBLISH_WINDOW_START, PUBLISH_WINDOW_END)
    today, sorted. Randomized (not evenly spaced) so posting doesn't look robotic — see
    pinterest_publish.py's module docstring on why this is browser automation, not the API.

    start is clamped to now (2026-10-09 fix): without this, a restart partway through the day
    (e.g. the Mac/bot was down since before today's schedule was ever computed) would still
    scatter times across the *full* configured window, including times already in the past —
    those become immediately "due" the moment publish_scheduler_loop next checks, firing
    several queued pins within the same ~120s tick right at startup instead of spread through
    the day. If the window has already fully elapsed for today (now >= end), this returns no
    times at all rather than cramming leftovers into "right now" — today just publishes
    nothing further, and a normal full-window schedule resumes tomorrow."""
    start = now.replace(
        hour=PUBLISH_WINDOW_START_HOUR, minute=PUBLISH_WINDOW_START_MINUTE, second=0, microsecond=0
    )
    end = now.replace(
        hour=PUBLISH_WINDOW_END_HOUR, minute=PUBLISH_WINDOW_END_MINUTE, second=0, microsecond=0
    )
    start = max(start, now)
    span = (end - start).total_seconds()
    if span <= 0:
        return []
    times = sorted(start + timedelta(seconds=random.uniform(0, span)) for _ in range(PUBLISH_TIMES_PER_DAY))
    return [t.isoformat() for t in times]


async def do_publish(app, item):
    """Runs one already-approved publish via Playwright (pinterest_publish.py) in a thread
    — it's sync and opens a real browser, so this keeps the bot's event loop responsive.
    Only ever called from handle_publish_decision's approved branch — never directly from
    the scheduler or /run_publish, which both go through send_publish_approval first (see
    module docstring: every real Pinterest publish needs an explicit Approve tap). On
    failure the item goes back to the front of publish_queue (not dropped, not published
    unattended) so it gets a fresh approval prompt at the next due slot; Anton is alerted
    either way since a broken selector won't fix itself."""
    try:
        url = await asyncio.to_thread(
            pinterest_publish.publish_pin,
            item["image_path"], item["title"], item["description"], item["link"], item["board"],
        )
        try:
            os.remove(item["image_path"])
        except OSError:
            pass
        await app.bot.send_message(CHAT_ID, f"Published to Pinterest: {item['title']}\n(landed on {url})")
    except Exception as e:
        logger.exception("Pinterest publish failed for %s", item.get("id"))
        st = state.load()
        st["publish_queue"].insert(0, item)
        state.save(st)
        await app.bot.send_message(
            CHAT_ID,
            f"Pinterest publish FAILED for \"{item['title']}\": {e}\n"
            "Left at the front of the queue — you'll get another approval prompt for it "
            "at the next scheduled slot, or send /run_publish to retry immediately after fixing it.",
        )


async def send_publish_approval(app, item):
    """Sends the queued image + title/description with Publish/Discard buttons — the gate
    between publish_queue and an actual Playwright run, see module docstring. Stores the
    item + message_id in state["pending_publish"] so handle_publish_decision knows what
    it's deciding on, and so a restart can re-send it (see post_init)."""
    with open(item["image_path"], "rb") as f:
        msg = await app.bot.send_photo(
            CHAT_ID,
            f,
            caption=(
                f"Ready to publish to Pinterest:\n\n{item['title']}\n\n{item['description']}\n\n"
                "Approve to actually post it now, or discard to drop it."
            ),
            reply_markup=publish_decision_keyboard(),
        )
    st = state.load()
    st["pending_publish"] = {**item, "message_id": msg.message_id}
    state.save(st)


async def handle_publish_decision(app, approved):
    st = state.load()
    pending = st["pending_publish"]
    if not pending:
        return "Nothing pending right now."
    await delete_message(app, pending.get("message_id"))
    st["pending_publish"] = None
    state.save(st)
    item = {k: v for k, v in pending.items() if k != "message_id"}
    if approved:
        await do_publish(app, item)
    else:
        try:
            os.remove(item["image_path"])
        except OSError:
            pass
        await app.bot.send_message(CHAT_ID, f"Discarded, not published: {item['title']}")
    return None


async def publish_scheduler_loop(app):
    """Independent of scheduler_loop/refill_scheduler_loop — at PUBLISH_TIMES_PER_DAY random
    times/day within the configured window, pops publish_queue's head and sends it for
    Anton's Approve/Discard (send_publish_approval) rather than publishing it directly,
    regardless of whether today's generation batch is idle/in-progress/done. Waits for any
    prior pending_publish to resolve before prompting about the next one — only one
    publish decision in flight at a time, same pattern as the main candidate/generation
    flow. PINTEREST_BOARD_NAME is optional (this account has no boards set up, confirmed
    2026-10-08) — empty means pins publish straight to the profile, see
    pinterest_publish.publish_pin."""
    while True:
        await asyncio.sleep(120)
        st = state.load()
        if st["pending_publish"]:
            continue
        now = datetime.now(TZ)
        today = now.strftime("%Y-%m-%d")
        if st["publish_date"] != today:
            st["publish_date"] = today
            st["publish_times_today"] = pick_publish_times(now)
            st["publish_times_done"] = []
            state.save(st)
            st = state.load()
        if not st["publish_queue"]:
            continue
        due = [
            t for t in st["publish_times_today"]
            if t not in st["publish_times_done"] and datetime.fromisoformat(t) <= now
        ]
        if not due:
            continue
        slot_time = min(due)
        st["publish_times_done"].append(slot_time)
        item = st["publish_queue"].pop(0)
        state.save(st)
        await send_publish_approval(app, item)


async def on_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()
    if update.effective_chat.id != CHAT_ID:
        return
    try:
        await query.edit_message_reply_markup(reply_markup=None)
    except Exception:
        pass
    if query.data in ("refill_yes", "refill_no"):
        await handle_refill_decision(context.application, query.data == "refill_yes")
        return
    if query.data in ("publish_approve", "publish_reject"):
        note = await handle_publish_decision(context.application, query.data == "publish_approve")
        if note:
            await context.application.bot.send_message(CHAT_ID, note)
        return
    if query.data.startswith("style:"):
        note = await handle_style_choice(context.application, query.data.removeprefix("style:"))
    elif query.data == "reject_photo":
        note = await handle_reject_photo(context.application)
    else:
        note = await handle_decision(context.application, query.data == "approve")
    if note:
        await context.application.bot.send_message(CHAT_ID, note)


async def on_text(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Typed approve/reject intentionally does NOT apply to a pending_publish decision
    (buttons only, see publish_decision_keyboard) — this shortcut is already overloaded
    for refill-confirmation and collage-decision, and a real Pinterest publish is
    deliberately the one decision in this bot you can't fat-finger via a stray "yes"."""
    if update.effective_chat.id != CHAT_ID or not update.message or not update.message.text:
        return
    text = update.message.text.strip().lower()
    if text in ("approve", "yes", "y"):
        approved = True
    elif text in ("reject", "no", "n"):
        approved = False
    else:
        return
    st = state.load()
    if st["refill_stage"] == "awaiting_confirmation":
        await handle_refill_decision(context.application, approved)
        return
    if st["stage"] == "candidates":
        if approved:
            await update.message.reply_text("Pick a style with the buttons above — typed approve doesn't apply here.")
            return
        note = await handle_reject_photo(context.application)
    else:
        note = await handle_decision(context.application, approved)
    if note:
        await update.message.reply_text(note)


